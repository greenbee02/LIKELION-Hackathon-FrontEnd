import type { ImageSourcePropType } from 'react-native';

/**
 * 리워드를 받으러 가는 곳의 마크 — 제목이 그 이름을 부를 때.
 *
 * **한때 `stores.ts` 였다.** 롯데백화점 하나뿐일 때는 "매장"이 맞는 이름이었는데, MCM HAUS 가
 * 들어오면서 그렇지 않게 됐다 — 백화점은 리워드를 파는 남의 매장이고 HAUS 는 하우스가 자기
 * 이름으로 여는 공간이다. 둘을 한 표에 담을 수 있는 것은 **가는 곳**이라는 성질 하나뿐이고,
 * 그것이 이 표식이 답하는 질문이기도 하다.
 *
 * **이 파일은 취약하고, 그것을 알고 쓴다.** 리워드에는 장소가 없다. `GET /rewards/progress`
 * 도 `/rewards/my` 도 장소를 실어 보내지 않고, 리워드가 아는 것은 컬렉션과 브랜드뿐이다.
 * 그래서 장소를 알아내는 유일한 방법이 **제목에 그 이름이 들어 있는지 보는 것**이고, 제목이
 * 바뀌면 표식은 조용히 사라진다. 사라져도 리워드는 그대로 읽히므로(테마 아이콘이 그 자리를
 * 받는다) 이 취약함이 화면을 깨뜨리지는 않는다.
 *
 * `rewards` 나 `events` 에 장소 열이 생기면 `match` 를 지우고 그 id 로 바꾼다.
 *
 * **`MCM` 을 그냥 찾지 않는 이유.** 이 데모의 리워드는 전부 MCM 의 것이고 제목 절반에 그
 * 세 글자가 들어 있다 — 브랜드 이름으로 매칭하면 여섯 줄 중 다섯에 같은 마크가 서고, 목록을
 * 갈라 보이게 하려고 만든 자리가 아무것도 가르지 않게 된다. 브랜드는 이 슬롯의 질문("어디로
 * 가는가")에 대한 답이 아니다. `MCM HAUS` 는 브랜드가 아니라 **공간의 이름**이라서 들어온다.
 *
 * **마크는 파일이고, 손으로 그리지 않는다.** `src/lib/mock/brand-marks.ts` 가 세운 규칙을
 * 그대로 따른다 — 남의 상표를 흉내 내어 그린 것은 틀린 로고이고, 틀린 로고는 없는 것보다
 * 나쁘다. 카드의 하우스 마크와 똑같이 **흰색으로 눕혀서** 쓴다: 리워드 패널이 컬렉션 색으로
 * 꽉 찬 면이라, 장소의 색을 그대로 얹으면 두 색이 나란히 놓여 둘 다 탁해진다.
 *
 * **그래서 이 파일에는 hex 가 없다.** 눕히는 일은 에셋에서 이미 끝나 있다.
 */

export type VenueMark = {
  /** 화면에는 나오지 않고 a11y 레이블로만 쓰인다 — 자리에 서는 것은 마크다. */
  label: string;
  /** **이미 흰색으로 눕혀진** 투명 배경 PNG — 색 면 위에 잉크처럼 앉는다. */
  mark: ImageSourcePropType;
};

/**
 * 제목에서 찾을 이름과, 찾았을 때 세울 마크. **위에서부터 먼저 맞는 것이 이긴다.**
 *
 * 순서에 뜻이 있다: `롯데백화점 본점 MCM 스페셜 프로모션` 은 두 이름을 다 갖고 있고, 그
 * 리워드를 받으러 가는 곳은 백화점이다. 남의 매장이 하우스의 공간보다 먼저 오는 이유가
 * 그것 하나다 — 더 구체적인 장소가 이긴다.
 *
 * **데이터에 실제로 나타나는 것만 넣는다.** 없는 장소의 마크를 미리 챙겨두면 그것은 폴백이
 * 아니라 창작이다.
 */
const VENUE_MARKS: { match: string; venue: VenueMark }[] = [
  {
    match: '롯데',
    venue: { label: '롯데백화점', mark: require('../../../assets/brand-marks/lotte.png') },
  },
  {
    match: 'MCM HAUS',
    venue: { label: 'MCM HAUS', mark: require('../../../assets/brand-marks/mcm.png') },
  },
];

/** 제목이 장소를 부르는가. 부르지 않으면 `null` 이고, 그러면 테마가 그 자리를 받는다. */
export function venueMarkFor(title: string): VenueMark | null {
  return VENUE_MARKS.find((v) => title.includes(v.match))?.venue ?? null;
}
