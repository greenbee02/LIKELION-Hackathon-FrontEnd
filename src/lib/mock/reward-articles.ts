/**
 * 리워드 한 건을 설명하는 글과 그 사진 — **전부 데모용으로 만든 것이다.**
 *
 * **왜 여기 있나.** 리워드에 붙은 글은 서버에 없다. `rewards.description` 과
 * `events.description` 이 DB 에는 있으나 어느 DTO 에도 실리지 않고, 프론트가 받는
 * `UnlockTarget` 은 `type` · `id` · `name` · `requiredPercentage` · `unlocked` 다섯 개가
 * 전부다(실서버 `/v3/api-docs` 로 확인). 기간도 장소도 사진도 마찬가지로 없다.
 *
 * 리워드 화면이 존재하는 이유가 **덜 모은 사람에게 마저 모을 이유를 주는 것**인데, 이름 한
 * 줄로는 그 이유가 서지 않는다.
 *
 * **`AGENTS.md` 의 "목 데이터는 없다"를 어기는 자리이고, 소유자의 지시로 어긴다.** 대신
 * 어기는 방식을 한 곳으로 좁혔다 — `card-art.ts` · `brand-marks.ts` 와 같은 폴더에 있고,
 * 백엔드가 이 필드들을 내보내는 날 이 파일 하나가 사라진다.
 *
 * **글은 포스터를 따른다.** 사진은 리워드마다 한 장씩 만들어진 세로 포스터에서 잘라 온
 * 것이고, 그 포스터에는 기간·장소·수량·유효기간이 이미 적혀 있다. 아래 글이 포스터와 다른
 * 말을 하면 화면이 제 사진과 싸우게 되므로, 날짜와 장소는 포스터에 적힌 것을 그대로 옮겼다.
 *
 * **모르는 리워드에는 아무 말도 하지 않는다.** 이름이 여기 없으면 `null` 이고, 화면은 글이
 * 아니라 조건만 남는다 — 종류별 일반 문구를 만들어 두면 여섯 건이 전부 같은 말을 하게 되고,
 * 그건 없는 것보다 나쁘다. 값이 없는 줄은 그리지 않는다는 이 앱의 규칙 그대로다.
 *
 * 키는 `UnlockTarget.name` — 시드가 주는 이름 그대로다.
 */
export type RewardArticle = {
  /**
   * 리워드 한 건의 포스터 — **자르지 않은 그대로.**
   *
   * 한 번 위쪽 사진만 잘라 썼다. 아래 검은 글판에 제목과 날짜가 인쇄되어 있어서 바로 밑의
   * 활자와 같은 말을 두 번 하게 된다는 이유였는데, **소유자가 포스터는 포스터로 다 보이길
   * 원했다.** 그것이 맞는 판단이다 — 이 그림은 배경 사진이 아니라 하우스가 이 행사를 위해
   * 만든 한 장이고, 아래 절반을 잘라내면 그 한 장이 아니게 된다.
   *
   * 겹치는 말은 남는다. 다만 인쇄된 글자는 화면 폭에서 작고 읽어 주는 기계에는 아무것도
   * 아니므로, `summary` 와 `schedule` 은 **같은 사실을 앱의 활자로 한 번 더** 적어 둔 것으로
   * 남긴다 — 지우면 그 사실이 그림 안에만 있게 된다.
   */
  cover: ImageSourcePropType;
  /**
   * 포스터의 가로 ÷ 세로.
   *
   * **틀을 그림에 맞춘다, 그림을 틀에 맞추지 않는다.** 화면이 비율 하나를 정해 두면 그와 다른
   * 그림은 그 순간 잘린다 — 지금 여섯 장이 모두 2:3 이지만, 그래서 값이 하나여도 되는 것이지
   * 화면이 2:3 을 알아도 되는 것은 아니다. 일곱 번째 포스터가 정사각형으로 와도 화면은 손댈
   * 곳이 없다.
   *
   * 값이 여기 적혀 있는 이유는 번들된 이미지의 크기를 화면이 물어볼 방법이 마땅치 않아서다.
   */
  coverAspect: number;
  /** 제목 바로 아래 한 줄 — 포스터의 부제 그대로. */
  summary: string;
  /**
   * 날짜·장소 — 글의 발신 정보에 해당한다.
   *
   * 라벨을 데이터에 둔 이유는 여섯 건이 서로 다른 것을 재기 때문이다. 전시와 프로모션은
   * "기간"과 "장소"를 갖지만, 실물 굿즈가 갖는 것은 "수량"과 "유효기간"이다. 화면이 라벨을
   * 고정하면 없는 축을 억지로 만들어야 한다.
   *
   * **대상 컬렉션과 해금 조건은 여기 없다.** 포스터에는 적혀 있지만 화면이 이미 두 번
   * 말한다 — 머리의 캡션과 "필요한 상품" 절이다.
   *
   * **날짜는 `2026.09.04` 로 고정 표기한다** — 이 앱이 날짜를 쓰는 방식 그대로이고, 기기의
   * 로케일에 따라 폭이 달라지면 두 줄이 어긋난다.
   */
  schedule: { label: string; value: string }[];
  /** 본문. 한 원소가 한 문단이다. */
  body: string[];
  /** 받게 되는 것들. 한 줄에 하나, 손에 잡히는 것부터. */
  benefits: string[];
};

